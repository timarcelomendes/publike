/** A divisão 12 a 33 (a indústria de transformação), menos o que já tem regra acima. */
function industria(cnae: string) {
  const d = Number(cnae.slice(0, 2));
  return d >= 12 && d <= 33;
}

export function categoriaDoRamo(cnae: string | null | undefined): Categoria | null {
  if (!cnae || !/^\d{7}$/.test(cnae)) return null;
  const regra = REGRAS.find(([inicio]) => cnae.startsWith(inicio));
  if (regra) return regra[1];
  return industria(cnae) ? "industria" : null;
}
